ALTER TABLE sala_membros
    ADD COLUMN IF NOT EXISTS pode_criar_tarefas BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS pode_comentar BOOLEAN NOT NULL DEFAULT TRUE;

ALTER TABLE tarefas
    ADD COLUMN IF NOT EXISTS cor VARCHAR(7) NOT NULL DEFAULT '#14B8A6',
    ADD COLUMN IF NOT EXISTS concluida BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS criador_id UUID REFERENCES usuarios(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS tarefa_conclusoes (
    id_usuario UUID NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    id_tarefa UUID NOT NULL REFERENCES tarefas(id) ON DELETE CASCADE,
    data_conclusao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id_usuario, id_tarefa)
);
